"""4.56.0: editing on a phone (#624, biggilottecassi: „wenn man am Handy auch was bearbeiten könnte“; the owner: „das man es nun auch wenn
man möchte editieren … auch am handy machen kann“). A phone still starts in the live view and in 3D (#299); the ☰ menu offers „Bearbeiten“
again. Then the tool bar is a strip (☰, 2D / 3D, undo, redo, save, the tools in one row that scrolls sideways), the rest of the bar opens
with ☰ without moving the picture, the side panel is a sheet at the bottom with what is selected first, a wall is drawn with the finger in
2D, „Mehr“ opens inside the screen; held sideways the strip is one row; back in the live view it is 3D again.
"""
own_pe = []
pgPE = b.new_page(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, extra_http_headers={"X-Remote-User-Name": "admin"})
pgPE.on("pageerror", lambda e: own_pe.append("PAGEERROR " + str(e)))
pgPE.goto(BASE + "?debug=1"); pgPE.wait_for_function("window.__fp && window.__fp.ready()", timeout=60000); pgPE.wait_for_timeout(1000)
body_pe = lambda c: pgPE.evaluate(f"document.body.classList.contains('{c}')")
walls_pe = lambda: pgPE.evaluate("window.__fp.layout.floors[window.__fp.floorIdx()].walls.length")
box_pe = lambda sel: pgPE.locator(sel).bounding_box()
check("phone edit (#624): a phone starts in the live view and in 3D, the tool bar folded", body_pe("live") and not body_pe("v-2d") and pgPE.locator("#toolbar").is_hidden())
pgPE.tap("#tbMenuBtn"); pgPE.wait_for_timeout(300)
check("phone edit: the ☰ menu offers „Bearbeiten“ (2D only while editing)", pgPE.locator("#modeSwitch [data-mode=edit]").is_visible() and pgPE.locator("#view2d").is_hidden())
pgPE.tap("#modeSwitch [data-mode=edit]"); pgPE.wait_for_timeout(1000)
check("phone edit: „Bearbeiten“ opens the editor and closes the menu", not body_pe("live") and not body_pe("tbopen"))
tb = box_pe("#toolbar")
tops = pgPE.evaluate("[...document.querySelectorAll('#tools .tBtn')].filter(b => b.offsetParent).map(b => Math.round(b.getBoundingClientRect().top))")
check("phone edit: the tool bar is a strip: ☰, 2D / 3D, undo, save and the tools", pgPE.locator("#tbMenuBtn").is_visible() and pgPE.locator("#view2d").is_visible()
      and pgPE.locator("#undoBtn").is_visible() and pgPE.locator("#saveBtn").is_visible() and pgPE.locator("#tools [data-tool=wall]").is_visible()
      and pgPE.locator("#modeSwitch").is_hidden() and pgPE.locator("#viewSplit").is_hidden() and pgPE.locator("#addFloor").is_hidden() and tb["height"] < 130, tb)
check("phone edit: the tools are one row that scrolls sideways", len(set(tops)) == 1 and pgPE.evaluate("(() => { const t = document.getElementById('tools'); return t.scrollWidth > t.clientWidth + 20; })()"), tops)
check("phone edit: no help for keys and mouse", pgPE.locator("#controlsHelp").is_hidden())
pgPE.tap("#view2d"); pgPE.wait_for_timeout(800)
check("phone edit: 2D can be chosen while editing", body_pe("v-2d") and pgPE.locator("#plan2d").is_visible())
pgPE.tap("#tools [data-tool=wall]"); pgPE.wait_for_timeout(300)
n0, pb = walls_pe(), box_pe("#plan2d")
xa, ya = pb["x"] + 40, pb["y"] + pb["height"] - 100
pgPE.touchscreen.tap(xa, ya); pgPE.wait_for_timeout(350)
pgPE.touchscreen.tap(xa + 120, ya); pgPE.wait_for_timeout(150)
pgPE.touchscreen.tap(xa + 120, ya); pgPE.wait_for_timeout(500)        # a double tap ends the chain
n1 = walls_pe()
check("phone edit: a wall is drawn with the finger (tap, tap, double tap)", n1 == n0 + 1, (n0, n1))
pgPE.tap("#undoBtn"); pgPE.wait_for_timeout(400)
check("phone edit: ↶ takes it back", walls_pe() == n0, walls_pe())
pgPE.tap("#tools [data-tool=select]"); pgPE.wait_for_timeout(200)
wid = pgPE.evaluate("(() => { const w = window.__fp.layout.floors[window.__fp.floorIdx()].walls[0]; window.__fp.select('wall', w.id); return w.id; })()")
pgPE.wait_for_timeout(400)
pp, ph, pn = box_pe("#props"), box_pe("#hint"), box_pe("#panel")
check("phone edit: the panel is a sheet at the bottom, what is selected comes first", pp and pn and pn["y"] > 844 * 0.45 and pp["y"] < (ph["y"] if ph else 9999) and pp["y"] < pn["y"] + 30, (pp, ph, pn))
pgPE.locator("#toolsMoreBtn").scroll_into_view_if_needed(); pgPE.tap("#toolsMoreBtn"); pgPE.wait_for_timeout(300)
mb, mo = box_pe("#toolsMore"), box_pe("#toolsMoreBtn")
check("phone edit: „Mehr“ opens under its button, inside the screen", pgPE.locator("#toolsMore").is_visible() and mb["x"] >= 0 and mb["x"] + mb["width"] <= 390
      and mb["y"] >= mo["y"] + mo["height"] and pgPE.locator("#toolsMore #importBtn").is_visible(), (mb, mo))
pgPE.tap("#toolsMoreBtn"); pgPE.wait_for_timeout(300)
check("phone edit: a second tap on „Mehr“ closes it", pgPE.locator("#toolsMore").is_hidden())
st0 = box_pe("#stage")
pgPE.tap("#tbMenuBtn"); pgPE.wait_for_timeout(400)
st1 = box_pe("#stage")
check("phone edit: ☰ opens the rest of the bar (Live, 2D + 3D, + Etage), without the tools", body_pe("tbopen") and pgPE.locator("#modeSwitch [data-mode=live]").is_visible()
      and pgPE.locator("#viewSplit").is_visible() and pgPE.locator("#addFloor").is_visible() and pgPE.locator("#tools").is_hidden())
check("phone edit: the picture does not jump while the menu is open", abs(st0["y"] - st1["y"]) < 2 and abs(st0["height"] - st1["height"]) < 2, (st0, st1))
pgPE.tap("#modeSwitch [data-mode=live]"); pgPE.wait_for_timeout(1000)
check("phone edit: back in the live view it is 3D again, the bar folded", body_pe("live") and not body_pe("v-2d") and pgPE.locator("#toolbar").is_hidden()
      and pgPE.evaluate("document.getElementById('app').style.paddingTop") == "")
pgPE.set_viewport_size({"width": 844, "height": 390}); pgPE.wait_for_timeout(800)
pgPE.tap("#tbMenuBtn"); pgPE.wait_for_timeout(300); pgPE.tap("#modeSwitch [data-mode=edit]"); pgPE.wait_for_timeout(1000)
tl, sv, tbl = box_pe("#tools [data-tool=select]"), box_pe("#saveBtn"), box_pe("#toolbar")
check("phone edit held sideways: one row with the tools, 2D / 3D and save", body_pe("phoneview") and not body_pe("live") and tbl["height"] < 80
      and abs((tl["y"] + tl["height"] / 2) - (sv["y"] + sv["height"] / 2)) < 20, (tl, sv, tbl))
pgPE.tap("#tbMenuBtn"); pgPE.wait_for_timeout(300); pgPE.tap("#modeSwitch [data-mode=live]"); pgPE.wait_for_timeout(500)
check("phone edit: no errors", not own_pe, own_pe)
pgPE.close()
